package com.monkopedia.kodemirror.state

import platform.Foundation.NSCharacterSet

private val alphanumeric = NSCharacterSet.alphanumericCharacterSet

// Kotlin's own Regex engine, which Native shares with Wasm, rejects `\p{Alphabetic}` and (as
// measured on Wasm) classifies astral code points by their low 16 bits, so use Foundation's
// L/M/N set by code point, adjusted to upstream's `[\p{Alphabetic}\p{Number}_]` (#415). The
// set's marks include 1,163 that aren't Alphabetic, such as U+0301 and the viramas, which are
// left out. The only Alphabetic code points outside L/M/N are the enclosed letters below
// (category So), identical in Unicode 10, 15 and 17. :autocomplete's findWords uses this through
// makeCategorizer.
internal actual fun hasWordChar(str: String): Boolean {
    var i = 0
    while (i < str.length) {
        val cp = codePointAt(str, i)
        if (cp == '_'.code ||
            isEnclosedLetter(cp) ||
            alphanumeric.longCharacterIsMember(cp.toUInt()) &&
            !isNonAlphabeticMark(cp)
        ) {
            return true
        }
        i += codePointSize(cp)
    }
    return false
}

// Circled, squared, negative circled and negative squared Latin letters.
private fun isEnclosedLetter(cp: Int): Boolean = cp in 0x24b6..0x24e9 ||
    cp in 0x1f130..0x1f149 ||
    cp in 0x1f150..0x1f169 ||
    cp in 0x1f170..0x1f189

/**
 * Whether [cp] is a combining mark (category M) that isn't Alphabetic. Generated with node
 * (Unicode 17) from `/\p{M}/u` and not `/\p{Alphabetic}/u`: 1,163 code points in 183 ranges.
 */
private fun isNonAlphabeticMark(cp: Int): Boolean {
    // Binary search for the last range starting at or before cp.
    var lo = 0
    var hi = NON_ALPHABETIC_MARKS.size / 2 - 1
    while (lo <= hi) {
        val mid = (lo + hi) ushr 1
        when {
            cp < NON_ALPHABETIC_MARKS[mid * 2] -> hi = mid - 1
            cp > NON_ALPHABETIC_MARKS[mid * 2 + 1] -> lo = mid + 1
            else -> return true
        }
    }
    return false
}

